<?php

declare(strict_types=1);

use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;

require_once dirname(__DIR__) . '/lib/pg_native_dump.php';

/**
 * Pure checks always run. The round trip needs a disposable PostgreSQL:
 *   SU_TEST_PG_HOST, SU_TEST_PG_PORT, SU_TEST_PG_USER, SU_TEST_PG_PASS, SU_TEST_PG_DB
 * (its schema `public` is wiped).
 */
final class PgNativeDumpTest extends TestCase
{
    /** @var \PgSql\Connection|null */
    private $conn = null;
    private string $file = '';

    protected function tearDown(): void
    {
        if ($this->conn !== null) {
            pg_close($this->conn);
        }
        if ($this->file !== '') {
            @unlink($this->file);
        }
    }

    #[Test]
    public function copyValuesUseTextCopyEscaping(): void
    {
        $this->assertSame('\N', pg_native_dump::copyValue(null));
        $this->assertSame('', pg_native_dump::copyValue(''));
        $this->assertSame('a\\tb\\nc\\rd\\\\e', pg_native_dump::copyValue("a\tb\nc\rd\\e"));
        $this->assertSame('\\\\N', pg_native_dump::copyValue('\N'), 'a literal \N string must not become NULL');
    }

    #[Test]
    public function roundTripRestoresSchemaDataAndSequences(): void
    {
        $this->connectOrSkip();
        $this->exec('DROP SCHEMA public CASCADE; CREATE SCHEMA public; SET search_path TO public;');
        $this->exec(<<<'SQL'
            CREATE TABLE fs_users (nick varchar(12) PRIMARY KEY, email text UNIQUE, admin boolean NOT NULL DEFAULT false);
            CREATE TABLE "Mixed Case" (
                id serial PRIMARY KEY,
                ident integer GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 5),
                nick varchar(12) REFERENCES fs_users (nick) ON DELETE CASCADE,
                note text COLLATE "C" DEFAULT 'it''s -- not a comment;',
                amount numeric(10,2) CHECK (amount >= 0),
                doubled numeric GENERATED ALWAYS AS (coalesce(amount, 0) * 2) STORED NOT NULL,
                raw bytea,
                created timestamp DEFAULT now()
            );
            CREATE INDEX mixed_note_idx ON "Mixed Case" (lower(note));
            INSERT INTO fs_users VALUES ('javier', 'j@example.com', true), ('ana', NULL, false);
            INSERT INTO "Mixed Case" (nick, note, amount, raw) VALUES
                ('javier', E'tab\there\nnew line \\ backslash; ñ €', 10.5, '\x00ff'::bytea),
                ('ana', NULL, 0, NULL),
                ('ana', '\N', 1, '');
        SQL);
        $before = $this->snapshot();

        $this->file = tempnam(sys_get_temp_dir(), 'pgdump') . '.sql.gz';
        $gz = gzopen($this->file, 'wb6');
        $tables = (new pg_native_dump($this->conn))->dump($gz, 'test');
        gzclose($gz);
        $this->assertSame(2, $tables);

        $this->exec("INSERT INTO fs_users VALUES ('intruso', NULL, false); DROP INDEX mixed_note_idx;");

        $gz = gzopen($this->file, 'rb');
        (new pg_native_dump($this->conn))->restore($gz);
        gzclose($gz);
        $this->exec('SET search_path TO public'); // the dump empties it for its session, like pg_dump

        $this->assertSame($before, $this->snapshot());
        // Sequences continue after the restored rows instead of colliding with them.
        $this->exec("INSERT INTO \"Mixed Case\" (nick, amount) VALUES ('ana', 3)");
        $this->assertSame(['4', '16'], array_values(pg_fetch_row(pg_query($this->conn, 'SELECT max(id), max(ident) FROM "Mixed Case"'))));
        $this->assertSame('C', pg_fetch_result(pg_query($this->conn,
            "SELECT collation_name FROM information_schema.columns WHERE table_name = 'Mixed Case' AND column_name = 'note'"), 0, 0));
        // The FK came back.
        $this->assertFalse(@pg_query($this->conn, "INSERT INTO \"Mixed Case\" (nick) VALUES ('nobody')"));
    }

    #[Test]
    public function objectsTheDumpCannotRecreateBlockTheBackup(): void
    {
        $this->connectOrSkip();
        $this->file = tempnam(sys_get_temp_dir(), 'pgdump') . '.sql.gz';
        foreach ([
            'vistas (1)' => 'CREATE VIEW public.v AS SELECT id FROM public.t;',
            'tipos propios' => "CREATE TYPE public.estado AS ENUM ('a', 'b');",
            'RLS' => 'ALTER TABLE public.t ENABLE ROW LEVEL SECURITY;',
            'otros esquemas' => 'CREATE SCHEMA other; CREATE VIEW other.v AS SELECT id FROM public.t;',
        ] as $expected => $setup) {
            $this->exec('DROP SCHEMA IF EXISTS other CASCADE; DROP SCHEMA public CASCADE; CREATE SCHEMA public; CREATE TABLE public.t (id int);' . $setup);
            $gz = gzopen($this->file, 'wb6');
            try {
                (new pg_native_dump($this->conn))->dump($gz, 'test');
                $this->fail($expected . ' must block the native backup');
            } catch (RuntimeException $e) {
                $this->assertStringContainsString($expected, $e->getMessage());
            } finally {
                gzclose($gz);
            }
        }
        $this->exec('DROP SCHEMA other CASCADE;');
    }

    #[Test]
    public function aTruncatedOrBrokenBackupLeavesTheDatabaseUntouched(): void
    {
        $this->connectOrSkip();
        $this->exec('DROP SCHEMA public CASCADE; CREATE SCHEMA public; CREATE TABLE keep (id int); INSERT INTO keep VALUES (1);');

        $this->file = tempnam(sys_get_temp_dir(), 'pgdump') . '.sql.gz';
        foreach ([
            "CREATE TABLE public.t (id int);\n", // no end marker: truncated
            "CREATE TABLE public.t (id int);\nCOPY public.t (id) FROM stdin;\nnot_an_int\n\\.\n" . pg_native_dump::END_MARKER . "\n",
        ] as $content) {
            file_put_contents($this->file, gzencode($content));
            $gz = gzopen($this->file, 'rb');
            try {
                (new pg_native_dump($this->conn))->restore($gz);
                $this->fail('restore must fail');
            } catch (RuntimeException $e) {
                $this->assertNotSame('', $e->getMessage());
            } finally {
                gzclose($gz);
            }
            $this->assertSame('1', pg_fetch_result(pg_query($this->conn, 'SELECT count(*) FROM public.keep'), 0, 0));
        }
    }

    private function connectOrSkip(): void
    {
        $host = (string) getenv('SU_TEST_PG_HOST');
        if ($host === '' || !function_exists('pg_connect')) {
            $this->markTestSkipped('Set SU_TEST_PG_HOST (and _PORT/_USER/_PASS/_DB) to run against a disposable PostgreSQL.');
        }
        $this->conn = pg_native_dump::connect(
            $host,
            (string) (getenv('SU_TEST_PG_PORT') ?: '5432'),
            (string) getenv('SU_TEST_PG_USER'),
            (string) getenv('SU_TEST_PG_PASS'),
            (string) getenv('SU_TEST_PG_DB')
        );
    }

    private function exec(string $sql): void
    {
        $this->assertNotFalse(@pg_query($this->conn, $sql), (string) pg_last_error($this->conn));
    }

    /** Data, columns, constraints and indexes, so any loss in the round trip shows up. */
    private function snapshot(): array
    {
        $out = [];
        foreach ([
            'SELECT * FROM fs_users ORDER BY nick',
            'SELECT id, ident, nick, note, amount, doubled, encode(raw, \'hex\') AS raw, created FROM "Mixed Case" ORDER BY id',
            "SELECT table_name, column_name, data_type, is_nullable, column_default, is_identity, is_generated
               FROM information_schema.columns WHERE table_schema = 'public' ORDER BY 1, ordinal_position",
            "SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint WHERE connamespace = 'public'::regnamespace AND contype <> 'n' ORDER BY 1",
            "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' ORDER BY 1",
        ] as $sql) {
            $out[] = pg_fetch_all(pg_query($this->conn, $sql)) ?: [];
        }

        return $out;
    }
}
