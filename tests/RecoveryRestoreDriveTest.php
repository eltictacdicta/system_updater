namespace Tests\SystemUpdater;

use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;

require_once dirname(__DIR__) . '/lib/recovery_view.php';

/**
 * RACC-07 — the console drives the restore that the canonical capability says
 * can complete, and offers no control it knows will be refused.
 *
 * The defect this replaces
 * -----------------------
 * The console opened `process_restore.php?action=start` with `new EventSource(...)`
 * and **no token**, so every restore was refused by `ensure_request_csrf()`
 * before doing anything — and `action=start` is the legacy single-request path
 * that the canonical "Stepped Resumable Restore" requirement states can never
 * complete on the production host, which kills the request after a few seconds.
 *
 * What is asserted, and why on the generated output
 * -------------------------------------------------
 * The driver is a function that returns the script the console emits, so the
 * assertions run over the bytes a browser would receive rather than over
 * `recovery.php`'s source: `su_csrf_token` on **every** request, `begin` first
 * and `chunk` after it, one URL builder (so no request can bypass the token),
 * no `action=start`, no `EventSource`, `busy` handled as a wait, and a bounded
 * retry that reports the checkpoint. A source-only assertion could be satisfied
 * by a second, dead branch; the emitted string is what runs.
 *
 * The backup rows are generated by the same file for the same reason: "every
 * group is listed" and "no restore control is offered when the console cannot
 * mint the token for it" are properties of the rendered table, not of a
 * template's intent.
 */
final class RecoveryRestoreDriveTest extends TestCase
{
    private const TOKEN = 'a3f1c8d29b4e6f708192a3b4c5d6e7f8091a2b3c4d5e6f708192a3b4c5d6e7f8';

    /**
     * The whole flow, in one case: the transport is the stepped one and every
     * request carries the console's token.
     */
    #[Test]
    public function theRestoreFlowIssuesBeginThenChunkWithTheTokenOnEveryRequest(): void
    {
        $driver = recovery_view_restore_driver(self::TOKEN);

        $this->assertStringContainsString(self::TOKEN, $driver, 'the driver carries the token the render minted');

        $this->assertStringContainsString(
            "runRestoreStep('begin')",
            $driver,
            'the flow starts with begin: the stepped protocol RACC-07 requires'
        );
        $this->assertStringContainsString(
            "runRestoreStep('chunk')",
            $driver,
            'and continues with chunk requests'
        );
        $this->assertLessThan(
            strpos($driver, "runRestoreStep('chunk')"),
            strpos($driver, "runRestoreStep('begin')"),
            'begin comes first: it arms the restore state every chunk then advances'
        );

        $this->assertStringNotContainsString(
            'action=start',
            $driver,
            'action=start is the single-request path that cannot complete on the production host'
        );
        $this->assertStringNotContainsString(
            'EventSource',
            $driver,
            'an SSE stream does not survive the host killing the request'
        );

        $this->assertSame(
            1,
            substr_count($driver, 'action='),
            'every request URL is built in exactly one place, so no path can miss the token'
        );
        $this->assertSame(
            1,
            substr_count($driver, 'fetch('),
            'and there is exactly one transport call'
        );
        $this->assertStringContainsString(
            'fetch(restoreUrl(',
            $driver,
            'the transport must use the URL builder that appends su_csrf_token'
        );
        $this->assertStringContainsString(
            "'&su_csrf_token=' + encodeURIComponent(suCsrfToken)",
            $driver,
            'and that builder is where the token is attached'
        );
    }

    /**
     * The two behaviours the stepped protocol owes the operator: a locked step is
     * a wait, and a cut transport resumes from the checkpoint instead of
     * pretending the restore failed.
     */
    #[Test]
    public function aLockedStepWaitsAndATransportCutResumesFromTheCheckpoint(): void
    {
        $driver = recovery_view_restore_driver(self::TOKEN);
        $code = $this->codeWithoutComments($driver);

        $this->assertStringContainsString('busy', $code, 'the server locks the step while another process holds it');
        $this->assertStringContainsString('2000', $code, 'and the client waits two seconds before asking again');

        $this->assertStringContainsString('restoreFailures', $code, 'transport failures are counted');
        $this->assertMatchesRegularExpression(
            '/restoreFailures\s*<=\s*5/',
            $code,
            'and bounded: an unbounded retry loop is a hung modal'
        );
        $this->assertStringContainsString(
            'runRestoreStep(\'chunk\')',
            $code,
            'the retry asks for another chunk, which resumes from the state on disk'
        );

        $this->assertStringContainsString('parseRestoreSseEvents', $code, 'the SSE framing is parsed from the body');
        $this->assertStringContainsString('errors_count', $code, 'errors_count decides failure');
        $this->assertStringContainsString('warnings_count', $code, 'and warnings_count is reported');
    }

    /**
     * U8.5, first half: the listing still works — every group, its name and its
     * timestamp, from an injected list (no database, no real backup files).
     */
    #[Test]
    public function everyBackupGroupIsListedWithItsNameAndTimestamp(): void
    {
        $rows = recovery_view_backup_rows($this->backupGroups(), true);

        $this->assertStringContainsString('backup-2026-10-20', $rows);
        $this->assertStringContainsString('backup-2026-10-21', $rows);
        $this->assertStringContainsString(
            date('d/m/Y H:i', 1761000000),
            $rows,
            'the timestamp is rendered in the operator format'
        );
        $this->assertStringContainsString(date('d/m/Y H:i', 1762000000), $rows);
        $this->assertStringContainsString('Completo', $rows, 'a group with a complete archive is labelled as such');
        $this->assertStringContainsString(
            'Solo backup completo soportado',
            $rows,
            'and a group without one says so instead of offering a control that cannot work'
        );
    }

    /**
     * U8.5, second half: no dead control. With a token the group that can be
     * restored offers controls wired to the driver; without one the console
     * offers none, because every request would be refused.
     */
    #[Test]
    public function restoreControlsAreOfferedOnlyWhenTheyCanCarryTheToken(): void
    {
        $withToken = recovery_view_backup_rows($this->backupGroups(), true);

        $this->assertSame(
            2,
            substr_count($withToken, 'restore-btn'),
            'the complete group offers "restore all" and "restore database", both wired to the driver'
        );
        $this->assertStringContainsString('data-file="backup-2026-10-20_complete.zip"', $withToken);
        $this->assertStringContainsString('data-type="complete"', $withToken);
        $this->assertStringContainsString('data-file="backup-2026-10-20_complete.zip"', $withToken);
        $this->assertStringContainsString('data-type="database"', $withToken);

        $withoutToken = recovery_view_backup_rows($this->backupGroups(), false);

        $this->assertSame(
            0,
            substr_count($withoutToken, 'restore-btn'),
            'with no token every restore would be refused, so none is rendered'
        );
        $this->assertStringContainsString('backup-2026-10-20', $withoutToken, 'the listing still works');
        $this->assertStringContainsString(
            'Restauración no disponible',
            $withoutToken,
            'and the operator is told why the controls are absent'
        );
    }

    /**
     * An empty list is a state the console has to render: no table rows, no
     * control, and a sentence instead of silence.
     */
    #[Test]
    public function anEmptyListRendersItsOwnMessage(): void
    {
        $rows = recovery_view_backup_rows([], true);

        $this->assertStringContainsString('No se encontraron copias de seguridad', $rows);
        $this->assertStringNotContainsString('restore-btn', $rows);
        $this->assertStringNotContainsString('<tr></tr>', $rows);
    }

    /**
     * The list comes from disk, and a backup file name is data — not markup.
     * The console is the one screen where an XSS would be worst: it runs behind
     * the emergency secret, with no panel to report it.
     */
    #[Test]
    public function backupNamesAreEscapedNotEchoed(): void
    {
        $groups = [[
            'base_name' => '<script>alert(1)</script>',
            'timestamp' => 1761000000,
            'complete' => ['name' => '"><img src=x onerror=alert(1)>'],
            'database' => null,
            'files' => null,
            'can_restore_complete' => true,
            'can_restore_files' => true,
            'can_restore_database' => true,
            'database_restore_file' => '"><img src=x onerror=alert(1)>',
        ]];

        $rows = recovery_view_backup_rows($groups, true);

        $this->assertStringNotContainsString('<script>alert(1)</script>', $rows, 'the group name is escaped');
        $this->assertStringNotContainsString('<img src=x', $rows, 'and so is every file name');
        $this->assertStringContainsString('&lt;script&gt;', $rows);
    }

    /**
     * @return array<int, array<string, mixed>>
     */
    private function backupGroups(): array
    {
        return [
            [
                'base_name' => 'backup-2026-10-20',
                'timestamp' => 1761000000,
                'complete' => ['name' => 'backup-2026-10-20_complete.zip'],
                'database' => null,
                'files' => null,
                'can_restore_complete' => true,
                'can_restore_files' => true,
                'can_restore_database' => true,
                'database_restore_file' => 'backup-2026-10-20_complete.zip',
            ],
            [
                'base_name' => 'backup-2026-10-21',
                'timestamp' => 1762000000,
                'complete' => null,
                'database' => ['name' => 'backup-2026-10-21_db.sql.gz'],
                'files' => ['name' => 'backup-2026-10-21_files.zip'],
                'can_restore_complete' => false,
                'can_restore_files' => true,
                'can_restore_database' => true,
                'database_restore_file' => 'backup-2026-10-21_db.sql.gz',
            ],
        ];
    }

    /**
     * The emitted script without its comments, so prose that names a construct
     * cannot satisfy an assertion about the code.
     */
    private function codeWithoutComments(string $source): string
    {
        $code = '';

        foreach (token_get_all($source) as $token) {
            if (is_array($token) && in_array($token[0], [T_COMMENT, T_DOC_COMMENT], true)) {
                continue;
            }

            $code .= is_array($token) ? $token[1] : $token;
        }

        return $code;
    }
}
